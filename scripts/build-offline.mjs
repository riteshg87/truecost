import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const outputDir = join(root, "public", "offline");
const assetsDir = join(outputDir, "assets");
const hash = (bytes) => createHash("sha256").update(bytes).digest("hex").slice(0, 16);
const source = await readFile(join(root, "offline", "index.template.html"), "utf8");
const css = await readFile(join(root, "offline", "styles.css"));
const swTemplate = await readFile(join(root, "offline", "sw-template.js"), "utf8");
const result = await build({
  absWorkingDir: root,
  entryPoints: ["offline/main.ts"],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: true,
  write: false,
  legalComments: "none",
});
const js = result.outputFiles[0].contents;
const jsPath = `/offline/assets/calculator.${hash(js)}.js`;
const cssPath = `/offline/assets/calculator.${hash(css)}.css`;
const html = source.replace("__CSS__", cssPath).replace("__JS__", jsPath);
const manifest = {
  version: hash(Buffer.concat([Buffer.from(html), Buffer.from(js), css, Buffer.from(swTemplate)])),
  assets: ["/offline/index.html", cssPath, jsPath, "/offline/manifest.json"],
};

await mkdir(assetsDir, { recursive: true });
for (const entry of await readdir(assetsDir)) await rm(join(assetsDir, entry), { force: true });
await writeFile(join(assetsDir, jsPath.split("/").at(-1)), js);
await writeFile(join(assetsDir, cssPath.split("/").at(-1)), css);
const manifestJson = `${JSON.stringify(manifest, null, 2)}\n`;
await writeFile(join(outputDir, "manifest.json"), manifestJson);
await writeFile(join(root, "lib", "pwa", "generated-version.ts"), `// Generated by scripts/build-offline.mjs.\nexport const OFFLINE_BUILD_VERSION = ${JSON.stringify(manifest.version)} as const;\n`);
await writeFile(join(outputDir, "index.html"), html);
const sw = swTemplate.replace("__VERSION__", manifest.version).replace("__ASSETS__", JSON.stringify(manifest.assets));
await writeFile(join(root, "public", "sw.js"), `${sw.trimEnd()}\n`);
console.log(`offline shell ${manifest.version}: ${manifest.assets.join(", ")}`);
